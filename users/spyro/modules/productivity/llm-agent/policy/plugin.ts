import { mkdirSync, readdirSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs"
import { homedir } from "node:os"
import { join } from "node:path"
// The seam, spliced in at deploy time. Home Manager flattens each file to its
// own store path, so this relative import would resolve against the Nix store
// and fail to load — silently, because the loader discards the cause. The
// deployed artefact is therefore the two files concatenated, and `nix flake
// check` asserts this import was the one thing removed.
import {
  isRepeatUnload,
  shouldUnload,
  type Decision,
  type InflightEntry,
  type Lease,
  type LeaseSet,
} from "./decision.js"

/**
 * The plugin half of the unload policy, ported to the opencode v2 plugin API.
 *
 * `decision.ts` holds the question; this file holds everything that answers it
 * in the real world: publishing what this process knows, reading what the
 * others published, and issuing the unload. Everything time-dependent, mutable
 * or effectful lives here so the seam stays pure.
 *
 * Four facts about the host, each established against opencode 2.2.6 (source
 * read at the pinned tag plus the live install) rather than read off a
 * changelog:
 *
 *  1. A plugin is a default export `{ id, setup(ctx) }`. `setup` returns a
 *     cleanup that runs when the plugin is unloaded. There is no `event` /
 *     `chat.params` hook object; the context exposes `ctx.event.subscribe()`
 *     (an async iterable) and `ctx.session.hook("context", …)` (the
 *     `chat.params` replacement, carrying `{ sessionID, model: { id,
 *     providerID } }`).
 *  2. The plugin is instantiated **per location** — once per open project in a
 *     process, not once per process. The policy state (sessions, lease, timer,
 *     heartbeat) is therefore a per-process singleton that each location's
 *     `setup` contributes to, and the full teardown is deferred to the last
 *     location leaving. Without the singleton one process would publish one
 *     lease per open project and run one unload timer per project.
 *  3. Events are delivered as `{ type, data }` — the payload is under `data`,
 *     not `properties`. `session.status` reports `busy` / `idle` / `retry`;
 *     `session.deleted` carries `data.sessionID`; streaming activity arrives as
 *     `session.text.delta` (the `message.part.delta` replacement).
 *  4. There is no `client.app.log` in the v2 context, so the policy writes its
 *     own log file under the state directory instead of the host's log.
 */

const SERVICE = "llm-agent-unload-policy"

/** How often the policy re-reads the lease set and re-decides. */
const TICK_MS = 5_000

/** opencode instantiates the plugin per location; this keys the per-process singleton. */
const SINGLETON = Symbol.for("llm-agent.unload-policy.singleton")

type Level = "debug" | "info" | "warn" | "error"

type Logger = (level: Level, message: string, extra?: Record<string, unknown>) => void

type PolicyConfig = {
  idleThresholdSeconds: number
  settleSeconds: number
  backend: string
  /** Provider id whose models are served locally. Owned by the registry. */
  localProviderId: string
}

type SessionState = {
  /** Whether the model most recently seen for this session is served locally. */
  local: boolean
  busy: boolean
  busyAt: number
  model: string | null
}

/**
 * Only the event shapes this policy reads.
 *
 * v2 delivers the payload under `data`, not `properties`. `data.sessionID` is
 * top-level for every session event, including `session.deleted` and
 * `session.text.delta`.
 */
type OpencodeEvent = {
  type: string
  data?: {
    sessionID?: string
    status?: { type: string }
  }
}

/** The model a session is running, as the `context` hook reports it. */
type ModelRef = { providerID?: string; id?: string }

// --- paths -----------------------------------------------------------------

function home(): string {
  return process.env.HOME && process.env.HOME.length > 0 ? process.env.HOME : homedir()
}

/** Per-user state, not a temporary directory: leases must outlive a reboot. */
function stateDir(): string {
  return join(process.env.XDG_STATE_HOME ?? join(home(), ".local", "state"), "llm-agent")
}

function leaseDir(): string {
  return join(stateDir(), "leases")
}

function leasePath(instanceId: string): string {
  return join(leaseDir(), `${instanceId}.json`)
}

function heartbeatPath(): string {
  return join(stateDir(), "heartbeat.json")
}

/** Generated by the flake from the registry, so the thresholds are data. */
function policyConfigPath(): string {
  return join(home(), ".config", "llama-swap", "unload-policy.json")
}

/** The policy's own log. The v2 context has no host log to write to. */
function policyLogPath(): string {
  return join(stateDir(), "policy.log")
}

// --- host probing ----------------------------------------------------------

let cachedBootId: string | null | undefined

/**
 * The kernel's boot id. A lease written before the last boot cannot be
 * attributed to a live process just because the pid has been reused, so the
 * boot id is part of what makes a lease trustworthy.
 */
function bootId(): string | null {
  if (cachedBootId !== undefined) return cachedBootId
  try {
    cachedBootId = readFileSync("/proc/sys/kernel/random/boot_id", "utf8").trim()
  } catch {
    cachedBootId = null
  }
  return cachedBootId
}

/**
 * Whether the process that wrote a lease still exists. A pid that exists but
 * was recycled belongs to somebody else, so the boot id has to agree too.
 */
function isProcessAlive(lease: { pid: number; bootId: string | null }): boolean {
  if (!Number.isInteger(lease.pid) || lease.pid <= 0) return false
  const current = bootId()
  if (current !== null && lease.bootId !== current) return false
  try {
    process.kill(lease.pid, 0)
    return true
  } catch (error) {
    // EPERM means the process exists but belongs to another user.
    return (error as { code?: string }).code === "EPERM"
  }
}

// --- lease publication -----------------------------------------------------

function writeJson(path: string, value: unknown): void {
  // Written through a temporary file so a reader never observes a half-written lease.
  const tmp = `${path}.tmp`
  writeFileSync(tmp, `${JSON.stringify(value)}\n`, { mode: 0o600 })
  renameSync(tmp, path)
}

function readLeaseSet(dir: string): LeaseSet {
  let names: string[]
  try {
    names = readdirSync(dir)
  } catch (error) {
    return { readable: false, error: `lease directory unreadable: ${String(error)}` }
  }

  const leases: Lease[] = []
  for (const name of names) {
    if (!name.endsWith(".json")) continue
    let parsed: Record<string, unknown>
    try {
      parsed = JSON.parse(readFileSync(join(dir, name), "utf8")) as Record<string, unknown>
    } catch (error) {
      // A lease that cannot be parsed is not a dead lease. It is an
      // unreadable lease set, and an unreadable lease set does not permit.
      return { readable: false, error: `lease '${name}' unreadable: ${String(error)}` }
    }
    leases.push({
      instanceId: String(parsed.instanceId ?? name),
      pid: Number(parsed.pid ?? -1),
      startedAt: Number(parsed.startedAt ?? 0),
      alive: isProcessAlive({ pid: Number(parsed.pid ?? -1), bootId: (parsed.bootId as string) ?? null }),
      lastLocalActivityAt: (parsed.lastLocalActivityAt as number | null) ?? null,
      busySince: (parsed.busySince as number | null) ?? null,
      idleSince: (parsed.idleSince as number | null) ?? null,
    })
  }
  return { readable: true, leases }
}

// --- the policy ------------------------------------------------------------

/**
 * The shared, per-process half of the policy.
 *
 * One process publishes one lease and runs one unload timer, no matter how many
 * projects (locations) it has open. Each location's `setup` contributes its
 * event stream and model-selection hook into this state; the full teardown is
 * deferred to the last location leaving.
 */
type SharedPolicy = {
  /** Handle one event from a location's stream. */
  onEvent(event: OpencodeEvent): void
  /** Handle a model selection from a location's `context` hook. */
  onContext(sessionID: string, model: ModelRef | undefined): void
  /** One evaluation of the policy. Lets a test drive the unload path directly. */
  tick(): Promise<{ decision: Decision; attempted: boolean }>
  /** A location started contributing. Starts the timer on the first. */
  addLocation(): void
  /** A location stopped contributing. Tears down on the last. */
  removeLocation(): Promise<void>
  /** Full teardown: stop the timer, remove the lease, last-one-out unload. */
  dispose(): Promise<void>
  /** Whether the policy has been fully torn down. A disposed policy is not reused. */
  isDisposed(): boolean
}

/**
 * Build the shared policy.
 *
 * Exported separately from the plugin below so the wiring can be reasoned
 * about — and re-run in a test — without going through opencode's loader.
 */
export function createUnloadPolicy(
  config: PolicyConfig,
  instanceId: string,
  now: () => number = Date.now,
): SharedPolicy {
  const log: Logger = (level, message, extra) => {
    // The v2 context has no host log, so the policy keeps its own. A missing
    // log file is not a failure: the heartbeat is the liveness signal, and this
    // is diagnostics for a human reading it later.
    const line = `${new Date(now()).toISOString()} [${SERVICE}] ${level}: ${message}${
      extra ? ` ${JSON.stringify(extra)}` : ""
    }`
    try {
      mkdirSync(stateDir(), { recursive: true, mode: 0o700 })
      writeFileSync(policyLogPath(), `${line}\n`, { flag: "a" })
    } catch {
      // A log that cannot be written is not worth failing the policy over.
    }
  }

  const pid = process.pid
  const boot = bootId()
  const startedAt = now()
  const sessions = new Map<string, SessionState>()

  let lastLocalActivityAt: number | null = null
  let busySince: number | null = null
  let idleSince: number | null = null
  let haveSeenStatus = false
  let lastUnloadAt: number | null = null
  let lastReason: string | null = null

  let locations = 0
  let timer: ReturnType<typeof setInterval> | null = null
  let disposed = false

  /**
   * Recompute the lease-level aggregates from the per-session states.
   *
   * `idleSince` is only advanced on the busy-to-idle *edge*. A turn that fails
   * or is cancelled can report idle more than once, and restarting the idle
   * clock on a duplicate would hold the resident model for a full threshold
   * after work that is already over.
   */
  function recompute(at: number): void {
    const all = [...sessions.values()]
    const busy = all.filter((s) => s.busy)
    const wasBusy = busySince !== null

    busySince = busy.length === 0 ? null : Math.min(...busy.map((s) => s.busyAt))

    if (busy.length > 0) {
      idleSince = null
    } else if (!haveSeenStatus || wasBusy) {
      idleSince = at
    }

    haveSeenStatus = true
  }

  function touchSession(sessionID: string, mutate: (state: SessionState, at: number) => void): void {
    const at = now()
    const state = sessions.get(sessionID) ?? { local: false, busy: false, busyAt: at, model: null }
    mutate(state, at)
    sessions.set(sessionID, state)
    recompute(at)
  }

  /** Record activity, but only when the session is running a local model. */
  function noteLocalActivity(state: SessionState): void {
    if (state.local) lastLocalActivityAt = now()
  }

  function publishLease(): void {
    const lease = {
      instanceId,
      pid,
      bootId: boot,
      startedAt,
      lastLocalActivityAt,
      busySince,
      idleSince,
    }
    try {
      mkdirSync(leaseDir(), { recursive: true, mode: 0o700 })
      writeJson(leasePath(instanceId), lease)
    } catch (error) {
      // Failing to publish is not fatal on its own, but it means this instance
      // cannot be seen by the others and so cannot contribute to a decision.
      log("warn", "could not publish lease", { error: String(error) })
    }
  }

  function writeHeartbeat(): void {
    try {
      mkdirSync(stateDir(), { recursive: true, mode: 0o700 })
      writeJson(heartbeatPath(), { at: now(), pid, instanceId })
    } catch (error) {
      log("warn", "could not write heartbeat", { error: String(error) })
    }
  }

  /**
   * Requests this process knows are running.
   *
   * At this tier the only source available is its own session state: a local
   * session that is busy has a request against the backend. The backend's own
   * in-flight stream is the authoritative answer and replaces this in #50; the
   * decision's shape does not change when it does.
   */
  function inflightEntries(): InflightEntry[] {
    const entries: InflightEntry[] = []
    for (const [sessionID, state] of sessions) {
      if (state.busy && state.local) entries.push({ id: sessionID, model: state.model })
    }
    return entries
  }

  async function unload(): Promise<void> {
    try {
      const response = await fetch(`${config.backend}/api/models/unload`, { method: "POST" })
      log(response.ok ? "info" : "warn", "unload requested", { status: response.status })
    } catch (error) {
      log("warn", "unload request failed", { error: String(error) })
    }
  }

  /** What one evaluation decided and did. Lets a test assert the action, not just the intent. */
  type TickResult = { decision: Decision; attempted: boolean }

  async function tick(): Promise<TickResult> {
    const at = now()
    writeHeartbeat()
    publishLease()

    const leaseSet = readLeaseSet(leaseDir())
    const decision = shouldUnload(leaseSet, inflightEntries(), at, {
      idleThresholdMs: config.idleThresholdSeconds * 1000,
      settleMs: config.settleSeconds * 1000,
    })

    if (decision.reason !== lastReason) {
      lastReason = decision.reason
      log("debug", "unload decision", { unload: decision.unload, reason: decision.reason })
    }

    if (!decision.unload) return { decision, attempted: false }
    // One idle epoch yields one unload attempt, however many times the session
    // reports idle or however often the timer fires.
    if (isRepeatUnload(lastUnloadAt, leaseSet)) return { decision, attempted: false }

    lastUnloadAt = at
    await unload()
    return { decision, attempted: true }
  }

  function startTimer(): void {
    if (timer !== null) return
    timer = setInterval(() => {
      void tick()
    }, TICK_MS)
    timer.unref()
  }

  function stopTimer(): void {
    if (timer !== null) {
      clearInterval(timer)
      timer = null
    }
  }

  /**
   * Full teardown: stop the timer, remove the lease, and — if this process was
   * the last one out — release the resident model.
   *
   * The unload is gated on the remaining leases: any live peer that is busy,
   * active, settling or unobserved vetoes, and an unreadable set refuses. An
   * empty set means we were the last one out, which is permission — not
   * evidence of breakage, as it would be on the tick.
   */
  async function dispose(): Promise<void> {
    if (disposed) return
    disposed = true
    stopTimer()
    try {
      rmSync(leasePath(instanceId), { force: true })
    } catch {
      // A lease left behind is stale, not harmful: the reader resolves
      // liveness from the process.
    }
    // Last one out closes the resident model. The tick only runs while this
    // process is alive, so without this an exiting last instance would leave
    // the model resident until the next opencode starts (backend ttl is 0).
    try {
      const leaseSet = readLeaseSet(leaseDir())
      if (!leaseSet.readable) return
      if (leaseSet.leases.filter((l) => l.alive).length === 0) {
        await unload()
        return
      }
      const decision = shouldUnload(leaseSet, [], now(), {
        idleThresholdMs: config.idleThresholdSeconds * 1000,
        settleMs: config.settleSeconds * 1000,
      })
      if (decision.unload) await unload()
    } catch (error) {
      log("warn", "dispose unload check failed", { error: String(error) })
    }
  }

  return {
    onEvent(event) {
      const at = now()
      const data = event.data
      if (event.type === "session.status") {
        const sessionID = data?.sessionID
        const status = data?.status?.type
        if (!sessionID || !status) return
        touchSession(sessionID, (state, at) => {
          if (status === "busy" || status === "retry") {
            if (!state.busy) state.busyAt = at
            state.busy = true
            noteLocalActivity(state)
          } else if (status === "idle") {
            state.busy = false
          }
        })
        // Published on the transition, not left to the next tick: a peer that
        // reads the lease up to five seconds late could decide to unload while
        // this process is already generating.
        publishLease()
        return
      }

      if (event.type === "session.deleted") {
        const sessionID = data?.sessionID
        if (sessionID) {
          sessions.delete(sessionID)
          recompute(at)
          publishLease()
        }
        return
      }

      // Any streaming traffic against a local session is activity against the
      // resident model. Without this a long generation would age past the
      // threshold while it was still streaming. These arrive many times a
      // second, so they move the in-memory timestamp only; the next tick
      // publishes it.
      if (event.type === "session.text.delta") {
        const sessionID = data?.sessionID
        if (!sessionID) return
        const state = sessions.get(sessionID)
        if (state) noteLocalActivity(state)
      }
    },

    onContext(sessionID, model) {
      const providerID = model?.providerID
      if (!providerID) return
      touchSession(sessionID, (state) => {
        state.local = providerID === config.localProviderId
        state.model = model?.id ?? null
      })
      const state = sessions.get(sessionID)
      // Only local traffic refreshes the lease. Cloud work must not hold the
      // resident model for the length of a conversation that never used it.
      if (state?.local) lastLocalActivityAt = now()
      publishLease()
    },

    tick,

    addLocation() {
      locations += 1
      if (locations === 1) {
        // The heartbeat exists because opencode discards the cause of a plugin
        // load failure: a plugin that throws on import produces no log at any
        // level. A missing heartbeat is what makes "the policy silently does
        // not exist" a visible state rather than an absence of evidence.
        writeHeartbeat()
        publishLease()
        log("info", "unload policy loaded", {
          pid,
          instanceId,
          idleThresholdSeconds: config.idleThresholdSeconds,
          settleSeconds: config.settleSeconds,
          backend: config.backend,
        })
        startTimer()
      }
    },

    async removeLocation() {
      locations = Math.max(0, locations - 1)
      if (locations === 0) await dispose()
    },

    dispose,

    isDisposed: () => disposed,
  }
}

/**
 * The opencode v2 plugin.
 *
 * opencode calls `setup` once per open project (location) in a process. Each
 * call contributes this location's event stream and model-selection hook into
 * the shared per-process policy, and returns a cleanup that removes the
 * contribution — tearing the policy down only when the last location leaves.
 */
export default {
  id: "llm-agent-unload-policy",

  async setup(ctx: {
    event: { subscribe: (options?: { types?: readonly string[]; signal?: AbortSignal }) => AsyncIterable<OpencodeEvent> }
    session: { hook: (name: string, callback: (input: { sessionID: string; model?: ModelRef }) => void) => Promise<{ dispose: () => Promise<void> }> }
  }): Promise<() => Promise<void>> {
    const globals = globalThis as unknown as Record<symbol, SharedPolicy | undefined>
    let policy = globals[SINGLETON]

    // A policy that was fully torn down (every location left) is not reused: a
    // later location gets a fresh one rather than re-activating a disposed timer.
    if (policy !== undefined && policy.isDisposed()) policy = undefined

    if (policy === undefined) {
      let config: PolicyConfig
      try {
        config = JSON.parse(readFileSync(policyConfigPath(), "utf8")) as PolicyConfig
      } catch (error) {
        // No policy is better than a guessed one. The thresholds are generated
        // from the registry; if they are missing, say so loudly and do nothing.
        const message = `unload policy disabled: ${policyConfigPath()} unreadable (${String(error)})`
        try {
          mkdirSync(stateDir(), { recursive: true, mode: 0o700 })
          writeFileSync(
            policyLogPath(),
            `${new Date().toISOString()} [${SERVICE}] error: ${message}\n`,
            { flag: "a" },
          )
        } catch {
          // A log that cannot be written is not worth failing the plugin over.
        }
        // Contribute nothing: no timer, no lease, no heartbeat.
        return async () => {}
      }
      const instanceId = `${process.pid}.${Math.random().toString(36).slice(2, 10)}`
      policy = createUnloadPolicy(config, instanceId)
      globals[SINGLETON] = policy
    }

    policy.addLocation()

    // This location's event stream, fed into the shared policy. The stream is
    // location-scoped, so each open project contributes its own sessions.
    const controller = new AbortController()
    void (async () => {
      try {
        for await (const event of ctx.event.subscribe({ signal: controller.signal })) {
          policy!.onEvent(event)
        }
      } catch {
        // The stream ending (location torn down) is the normal path; an error
        // here means this location contributes no more, which the cleanup
        // already accounts for.
      }
    })()

    // The model-selection hook: the `chat.params` replacement.
    let registration: { dispose: () => Promise<void> } | undefined
    try {
      registration = await ctx.session.hook("context", (input) => {
        policy!.onContext(input.sessionID, input.model)
      })
    } catch {
      // A hook that cannot be registered means this location reports no model
      // selections; the policy still runs on the other locations' data.
    }

    return async () => {
      controller.abort()
      try {
        await registration?.dispose()
      } catch {
        // Disposing a hook that already ran is not an error worth surfacing.
      }
      await policy!.removeLocation()
    }
  },
}
